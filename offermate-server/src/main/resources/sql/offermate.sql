    is_read TINYINT NOT NULL DEFAULT 0 COMMENT '是否已读：0未读 1已读',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='通知表';

CREATE TABLE IF NOT EXISTS interview_invitation (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    seeker_id BIGINT NOT NULL COMMENT '求职者ID',
    recruiter_id BIGINT NOT NULL COMMENT '招聘者ID',
    company_id BIGINT NOT NULL COMMENT '企业ID',
    job_id BIGINT NOT NULL COMMENT '岗位ID',
    delivery_id BIGINT NOT NULL COMMENT '投递记录ID',
    interview_time DATETIME NOT NULL COMMENT '面试时间',
    address VARCHAR(255) DEFAULT NULL COMMENT '面试地址',
    contact_name VARCHAR(50) DEFAULT NULL COMMENT '联系人',
    contact_phone VARCHAR(20) DEFAULT NULL COMMENT '联系电话',
    remark VARCHAR(500) DEFAULT NULL COMMENT '备注',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '状态：1待确认 2已接受 3已拒绝 4已取消',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_seeker_id (seeker_id),
    KEY idx_recruiter_id (recruiter_id),
    KEY idx_delivery_id (delivery_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='面试邀请表';

CREATE TABLE IF NOT EXISTS ai_interview_session (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id BIGINT NOT NULL COMMENT '用户ID',
    job_id BIGINT NOT NULL COMMENT '岗位ID',
    resume_id BIGINT DEFAULT NULL COMMENT '简历ID',
    title VARCHAR(100) DEFAULT NULL COMMENT '会话标题',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '状态：1进行中 2已完成',
    total_score INT DEFAULT NULL COMMENT '总评分',
    report TEXT COMMENT '面试报告',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_user_id (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI模拟面试会话表';

CREATE TABLE IF NOT EXISTS ai_interview_message (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    session_id BIGINT NOT NULL COMMENT '面试会话ID',
    role VARCHAR(20) NOT NULL COMMENT '角色：user/assistant/system',
    content TEXT NOT NULL COMMENT '消息内容',
    score INT DEFAULT NULL COMMENT '本轮评分',
    suggestion TEXT COMMENT '本轮建议',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    KEY idx_session_id (session_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI模拟面试消息表';

CREATE TABLE IF NOT EXISTS operation_log (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id BIGINT DEFAULT NULL COMMENT '用户ID',
    username VARCHAR(50) DEFAULT NULL COMMENT '用户名',
    role TINYINT DEFAULT NULL COMMENT '角色',
    module VARCHAR(50) NOT NULL COMMENT '模块',
    operation VARCHAR(100) NOT NULL COMMENT '操作',
    method VARCHAR(255) DEFAULT NULL COMMENT '执行方法',
    request_uri VARCHAR(255) DEFAULT NULL COMMENT '请求路径',
    request_method VARCHAR(20) DEFAULT NULL COMMENT '请求方式',
    ip VARCHAR(50) DEFAULT NULL COMMENT 'IP地址',
    params TEXT COMMENT '请求参数',
    result TEXT COMMENT '返回结果',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '状态：1成功 0失败',
    error_msg TEXT COMMENT '错误信息',
    cost_time BIGINT DEFAULT NULL COMMENT '耗时毫秒',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    KEY idx_user_id (user_id),
    KEY idx_module (module),
    KEY idx_operation (operation),
    KEY idx_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='操作日志表';

