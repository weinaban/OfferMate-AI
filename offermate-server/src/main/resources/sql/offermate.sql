CREATE DATABASE IF NOT EXISTS offermate DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE offermate;

CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    username VARCHAR(50) NOT NULL UNIQUE COMMENT '用户名',
    password VARCHAR(100) NOT NULL COMMENT '登录密码',
    phone VARCHAR(20) DEFAULT NULL COMMENT '手机号',
    avatar VARCHAR(255) DEFAULT NULL COMMENT '用户头像',
    role TINYINT NOT NULL DEFAULT 1 COMMENT '角色：1求职者 2招聘者 3管理员',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '状态：1正常 0禁用',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='系统用户表';

CREATE TABLE IF NOT EXISTS company (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id BIGINT NOT NULL COMMENT '招聘者用户ID',
    company_name VARCHAR(100) NOT NULL COMMENT '企业名称',
    logo VARCHAR(255) DEFAULT NULL COMMENT '企业Logo',
    industry VARCHAR(50) DEFAULT NULL COMMENT '所属行业',
    scale VARCHAR(50) DEFAULT NULL COMMENT '公司规模',
    address VARCHAR(255) DEFAULT NULL COMMENT '企业地址',
    intro TEXT COMMENT '企业介绍',
    audit_status TINYINT NOT NULL DEFAULT 0 COMMENT '审核状态：0待审核 1通过 2拒绝',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_company_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='企业信息表';

CREATE TABLE IF NOT EXISTS job_position (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    company_id BIGINT NOT NULL COMMENT '企业ID',
    recruiter_id BIGINT NOT NULL COMMENT '招聘者ID',
    title VARCHAR(100) NOT NULL COMMENT '岗位名称',
    salary_min INT DEFAULT NULL COMMENT '最低薪资',
    salary_max INT DEFAULT NULL COMMENT '最高薪资',
    city VARCHAR(50) DEFAULT NULL COMMENT '工作城市',
    experience VARCHAR(50) DEFAULT NULL COMMENT '经验要求',
    education VARCHAR(50) DEFAULT NULL COMMENT '学历要求',
    tags VARCHAR(255) DEFAULT NULL COMMENT '技能标签',
    description TEXT COMMENT '岗位描述',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '岗位状态：1招聘中 0已下架',
    audit_status TINYINT NOT NULL DEFAULT 0 COMMENT '审核状态：0待审核 1通过 2拒绝',
    view_count INT NOT NULL DEFAULT 0 COMMENT '浏览量',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='岗位表';

CREATE TABLE IF NOT EXISTS resume (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id BIGINT NOT NULL COMMENT '用户ID',
    title VARCHAR(100) NOT NULL COMMENT '简历名称',
    real_name VARCHAR(50) DEFAULT NULL COMMENT '姓名',
    phone VARCHAR(20) DEFAULT NULL COMMENT '电话',
    email VARCHAR(100) DEFAULT NULL COMMENT '邮箱',
    education VARCHAR(50) DEFAULT NULL COMMENT '学历',
    experience_year INT DEFAULT NULL COMMENT '工作年限',
    skill TEXT COMMENT '技能描述',
    project_exp TEXT COMMENT '项目经历',
    self_intro TEXT COMMENT '自我评价',
    is_default TINYINT NOT NULL DEFAULT 0 COMMENT '是否默认简历：1是 0否',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='在线简历表';

CREATE TABLE IF NOT EXISTS job_delivery (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id BIGINT NOT NULL COMMENT '求职者ID',
    job_id BIGINT NOT NULL COMMENT '岗位ID',
    company_id BIGINT NOT NULL COMMENT '企业ID',
    resume_id BIGINT NOT NULL COMMENT '简历ID',
    status TINYINT NOT NULL DEFAULT 1 COMMENT '投递状态：1已投递 2已查看 3感兴趣 4邀面试 5不合适 6已录用',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_user_job (user_id, job_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='岗位投递表';

