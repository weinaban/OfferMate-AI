CREATE TABLE IF NOT EXISTS chat_session (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    seeker_id BIGINT NOT NULL COMMENT '求职者ID',
    recruiter_id BIGINT NOT NULL COMMENT '招聘者ID',
    job_id BIGINT NOT NULL COMMENT '岗位ID',
    last_message VARCHAR(255) DEFAULT NULL COMMENT '最后一条消息',
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_session (seeker_id, recruiter_id, job_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='聊天会话表';

CREATE TABLE IF NOT EXISTS chat_message (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    session_id BIGINT NOT NULL COMMENT '会话ID',
    sender_id BIGINT NOT NULL COMMENT '发送人ID',
    receiver_id BIGINT NOT NULL COMMENT '接收人ID',
    content TEXT NOT NULL COMMENT '消息内容',
    msg_type TINYINT NOT NULL DEFAULT 1 COMMENT '消息类型：1文本',
    is_read TINYINT NOT NULL DEFAULT 0 COMMENT '是否已读：0未读 1已读',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    KEY idx_session_time (session_id, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='聊天消息表';

CREATE TABLE IF NOT EXISTS ai_call_log (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
